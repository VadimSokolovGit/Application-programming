        "192.168.01.1",         # ведущий ноль
        "192.168.00.1",         # двойной ноль
        "192.168.1.a",          # буква
        "192.168..1",           # пустой октет
        "192.168.1.-1",         # отрицательное число
        " 192.168.1.1",         # пробел в начале
